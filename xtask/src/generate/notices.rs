use crate::{archive, process::Runner};
use anyhow::{Context, Result, ensure};
use serde::Deserialize;
use std::{
	collections::{BTreeMap, BTreeSet},
	fs,
	path::{Path, PathBuf},
};

#[derive(Deserialize)]
struct Package {
	name: String,
	version: String,
	source: Option<String>,
	license: Option<String>,
	license_file: Option<String>,
	manifest_path: PathBuf,
}
#[derive(Deserialize)]
struct Metadata {
	packages: Vec<Package>,
}

fn collect(path: &Path, files: &mut BTreeSet<PathBuf>) -> Result<()> {
	if path.is_file() {
		files.insert(path.to_owned());
	} else if path.is_dir() {
		for entry in fs::read_dir(path)? {
			collect(&entry?.path(), files)?;
		}
	}
	Ok(())
}

fn license_files(root: &Path, package: &Package) -> Result<BTreeSet<PathBuf>> {
	let folder = package
		.manifest_path
		.parent()
		.context("Manifest has no parent")?;
	let mut files = BTreeSet::new();
	for entry in fs::read_dir(folder)? {
		let entry = entry?;
		let name = entry.file_name().to_string_lossy().to_lowercase();
		if [
			"license",
			"licence",
			"copying",
			"copyright",
			"notice",
			"authors",
		]
		.iter()
		.any(|prefix| name.starts_with(prefix))
		{
			collect(&entry.path(), &mut files)?;
		}
	}
	if let Some(file) = &package.license_file {
		files.insert(folder.join(file));
	}
	let supplement = root
		.join("licenses/dependency-supplements")
		.join(format!("{}-{}.txt", package.name, package.version));
	if supplement.exists() {
		files.insert(supplement);
	}
	Ok(files)
}

pub fn run(runner: &Runner) -> Result<()> {
	let mut metadata: Metadata =
		serde_json::from_str(&runner.output(runner.command("cargo").args([
			"metadata",
			"--locked",
			"--offline",
			"--format-version=1",
		]))?)?;
	metadata.packages.retain(|package| package.source.is_some());
	metadata
		.packages
		.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
	let mut records = Vec::new();
	let mut texts = BTreeMap::new();
	for package in &metadata.packages {
		records.extend([
			format!("{} {}", package.name, package.version),
			format!(
				"License declaration: {}",
				package.license.as_deref().unwrap_or("None")
			),
			format!(
				"Source: https://crates.io/crates/{}/{}",
				package.name, package.version
			),
		]);
		let files = license_files(&runner.root, package)?;
		ensure!(
			!files.is_empty(),
			"Dependency missing bundled notices: {}",
			package.name
		);
		for path in files {
			// Python's text reader normalized CRLF; preserve the existing notice hashes.
			let text = fs::read_to_string(&path)?
				.replace("\r\n", "\n")
				.replace('\r', "\n");
			let hash = archive::digest_bytes(text.as_bytes());
			texts.insert(hash.clone(), text);
			records.push(format!(
				"Notice: {} [sha256:{hash}]",
				path.file_name().unwrap().to_string_lossy()
			));
		}
		records.push(String::new());
	}
	let mut lines: Vec<String> = [
		"tuxd dependency license notices",
		"",
		"Generated by cargo xtask generate notices from Cargo.lock.",
		"Includes all locked packages and target platforms, including build dependencies.",
		"Declarations list upstream licensing alternatives; retained texts are not relicensed.",
		"Not a substitute for supplying corresponding source when distributing binaries.",
		"",
	]
	.into_iter()
	.map(str::to_owned)
	.collect();
	lines.extend(records);
	for (hash, text) in texts {
		lines.extend([format!("===== sha256:{hash} ====="), text, String::new()]);
	}
	fs::write(
		runner.root.join("licenses/dependencies.txt"),
		lines.join("\n"),
	)?;
	println!(
		"Retained notices for {} dependency packages",
		metadata.packages.len()
	);
	Ok(())
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn retains_nested_custom_and_supplemental_notices_once() -> Result<()> {
		let temp = tempfile::tempdir()?;
		let root = temp.path();
		let crate_dir = root.join("crate");
		fs::create_dir_all(crate_dir.join("LICENSES"))?;
		for name in ["LICENSE", "LICENSES/third-party", "CUSTOM"] {
			fs::write(crate_dir.join(name), "notice")?;
		}
		let supplements = root.join("licenses/dependency-supplements");
		fs::create_dir_all(&supplements)?;
		fs::write(supplements.join("example-1.0.0.txt"), "supplement")?;
		let mut package = Package {
			name: "example".into(),
			version: "1.0.0".into(),
			source: Some("registry".into()),
			license: None,
			license_file: Some("CUSTOM".into()),
			manifest_path: crate_dir.join("Cargo.toml"),
		};
		assert_eq!(license_files(root, &package)?.len(), 4);
		package.license_file = Some("LICENSE".into());
		assert_eq!(license_files(root, &package)?.len(), 3);
		Ok(())
	}
}
