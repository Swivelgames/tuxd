#!/usr/bin/env python3
"""Collect locked dependency license declarations and bundled notices offline."""
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def license_files(package):
	folder = Path(package["manifest_path"]).parent
	files = set()
	for entry in folder.iterdir():
		if entry.name.lower().startswith(("license", "licence", "copying", "copyright", "notice", "authors")):
			if entry.is_file():
				files.add(entry)
			elif entry.is_dir():
				files.update(path for path in entry.rglob("*") if path.is_file())
	if package.get("license_file"):
		files.add(folder / package["license_file"])
	supplement = ROOT / "licenses/dependency-supplements" / f'{package["name"]}-{package["version"]}.txt'
	if supplement.exists():
		files.add(supplement)
	return sorted(files)


def main():
	metadata = json.loads(subprocess.check_output(
		["cargo", "metadata", "--locked", "--offline", "--format-version=1"], cwd=ROOT,
	))
	packages = sorted(
		(package for package in metadata["packages"] if package["source"] is not None),
		key=lambda package: (package["name"], package["version"]),
	)
	texts = {}
	records = []
	missing = []
	for package in packages:
		name = f'{package["name"]} {package["version"]}'
		records.extend([name, f'License declaration: {package["license"]}',
			f'Source: https://crates.io/crates/{package["name"]}/{package["version"]}'])
		files = license_files(package)
		if not files:
			missing.append(name)
		for path in files:
			text = path.read_text(encoding="utf-8")
			identity = hashlib.sha256(text.encode()).hexdigest()
			texts[identity] = text
			records.append(f'Notice: {path.name} [sha256:{identity}]')
		records.append("")
	if missing:
		raise SystemExit("Dependencies missing bundled license files: " + ", ".join(missing))

	output = [
		"tuxd dependency license notices", "",
		"Generated by scripts/update_dependency_notices.py from Cargo.lock.",
		"Includes all locked packages and target platforms, including build dependencies.",
		"Declarations list upstream licensing alternatives; retained texts are not relicensed.",
		"Not a substitute for supplying corresponding source when distributing binaries.", "",
		*records,
	]
	for identity, text in sorted(texts.items()):
		output.extend([f"===== sha256:{identity} =====", text, ""])
	path = ROOT / "licenses/dependencies.txt"
	path.parent.mkdir(exist_ok=True)
	path.write_text("\n".join(output))
	print(f"Retained notices for {len(packages)} dependency packages in {path.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
