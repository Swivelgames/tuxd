fn rgb(hex: u32) -> Color {
	Color::Rgb((hex >> 16) as u8, (hex >> 8) as u8, hex as u8)
}

// Upstream palette sources and role adaptations: .work/initiatives/themes/presets.md.
struct Palette {
	surface: u32,
	field: u32,
	text: u32,
	muted: u32,
	selected: u32,
	focus: u32,
	accent: u32,
	parameter: u32,
	escape: u32,
	error: u32,
}

fn palette(colors: Palette) -> Theme {
	Theme {
		surface: rgb(colors.surface),
		field: rgb(colors.field),
		text: rgb(colors.text),
		muted: rgb(colors.muted),
		border: rgb(colors.muted),
		selected: rgb(colors.selected),
		selected_text: rgb(colors.text),
		focus: rgb(colors.focus),
		inactive_indicator: rgb(colors.muted),
		accent: rgb(colors.accent),
		error: rgb(colors.error),
		syntax_sequence: rgb(colors.accent),
		syntax_parameter: rgb(colors.parameter),
		syntax_escape: rgb(colors.escape),
		syntax_separator: rgb(colors.muted),
		syntax_whitespace: rgb(colors.accent),
		..Theme::default()
	}
}

